#!/usr/bin/env python3
"""Longitudinal domain diagnosis and a proposed regularization.

High-precision one-mode homogeneous matrices, not a purported invariant
sector of the full six-mode Hamiltonian. Finite spectral growth is evidence
against assuming uniform initial energy; it is not an asymptotic theorem.
The regularized classical flow below is generated by L_epsilon itself, not
by the physical Hamiltonian.
"""
import hashlib
import json
from pathlib import Path

import mpmath as mp
import sympy as sy


def homogeneous_cases(R, dps, epsilons):
    with mp.workdps(dps):
        h = mp.mpf('.2')
        d = R+1
        A = mp.matrix(d)
        for n in range(1,d):
            A[n-1,n] = mp.sqrt(n)
        S = mp.sqrt(h/2)*(A+A.T)
        P = -1j*mp.sqrt(h/2)*(A-A.T)
        D,C = mp.expm(-S/2),mp.expm(S)
        rows = []
        for epsilon in epsilons:
            e = mp.mpf(epsilon)
            mobility = D*D if e == 0 else (C+e*mp.eye(d))**-1
            L = (mobility*P+P*mobility)/2
            hermitian = mp.norm(L-L.H)/max(1,mp.norm(L))
            values,U = mp.eighe(L)
            residual = mp.norm(L*U-U*mp.diag(values))/max(1,mp.norm(L))
            orthogonal = mp.norm(U.H*U-mp.eye(d))
            vector = D[:,0]
            logterms = []
            for k in range(d):
                overlap = sum(mp.conj(U[j,k])*vector[j] for j in range(d))
                if overlap != 0:
                    logterms.append(values[k]+2*mp.log(abs(overlap)))
            peak = max(logterms)
            logpotential = peak+mp.log(sum(mp.exp(x-peak) for x in logterms))
            logenergy = mp.log(C[0,0]/2+mp.exp(logpotential))
            assert max(hermitian,residual,orthogonal) < mp.mpf(10)**(-dps+8)
            rows.append(dict(capacity=R,precision_digits=dps,epsilon=epsilon,hbar='0.2',
                log_vacuum_potential=mp.nstr(logpotential,45),log_vacuum_energy=mp.nstr(logenergy,45),
                largest_longitudinal_eigenvalue=mp.nstr(values[d-1],30),
                hermitian_relative_error=mp.nstr(hermitian,8),
                eigenvector_relative_residual=mp.nstr(residual,8),orthonormality_error=mp.nstr(orthogonal,8)))
            print('R',R,'digits',dps,'epsilon',epsilon,'log(Vvac)',mp.nstr(logpotential,16),flush=True)
        return rows


def chart_and_symbolic_checks():
    s,k,e = sy.symbols('s k e',real=True)
    c = sy.exp(s)
    psi = sy.exp(s/2-k*c)
    assert sy.simplify(sy.exp(-s)*(sy.diff(psi,s)-psi/2)+k*psi) == 0
    q = c+e*s
    weight = sy.sqrt(c+e)
    phi = sy.Function('phi')
    pull = weight*phi(q)
    differential = sy.diff(pull,s)/(c+e)-c*pull/(2*(c+e)**2)
    assert sy.simplify(differential-weight*sy.Subs(sy.Derivative(phi(s),s),s,q)) == 0
    rows = []
    with mp.workdps(80):
        for epsilon in ['0.01','0.1','0.5']:
            eps = mp.mpf(epsilon)
            c0 = mp.mpf(1)
            q0 = c0+eps*mp.log(c0)
            def flow(t):
                return eps*mp.lambertw(mp.exp((q0+t)/eps)/eps).real
            for tau in [-5,-1,0,1,5]:
                ct = flow(tau)
                assert ct > 0
                chart_error = abs(ct+eps*mp.log(ct)-(q0+tau))
                derivative_error = abs(mp.diff(flow,tau)-ct/(ct+eps))
                assert max(chart_error,derivative_error) < mp.mpf('1e-70')
                a = min(ct,mp.mpf('.2'))
                speed_error = abs(ct/(ct+eps)-1)
                mobility_error = abs(1/(ct+eps)-1/ct)
                assert speed_error <= eps/a
                assert mobility_error <= eps/a**2
                rows.append(dict(epsilon=epsilon,translation_parameter=tau,clock=mp.nstr(ct,35),
                    chart_identity_error=mp.nstr(chart_error,8),derivative_error=mp.nstr(derivative_error,8)))
    return rows


def main():
    cases = []
    for R in [16,32,48,64]:
        cases.extend(homogeneous_cases(R,70,['0','0.1']))
    precise = homogeneous_cases(64,110,['0','0.1'])
    comparison = []
    with mp.workdps(110):
        for row in precise:
            previous = next(c for c in cases if c['capacity']==64 and c['epsilon']==row['epsilon'])
            error = abs(mp.mpf(row['log_vacuum_potential'])-mp.mpf(previous['log_vacuum_potential']))
            assert error < mp.mpf('1e-30'),error
            comparison.append(dict(epsilon=row['epsilon'],log_potential_precision_difference=mp.nstr(error,12)))
    cases.extend(precise)
    flow = chart_and_symbolic_checks()
    root = Path(__file__).resolve().parents[1]
    previous = json.loads((root/'data/inverse_clock_parity_audit.json').read_text())
    sources = list(previous['source_sha256'])+['scripts/longitudinal_domain_audit.py']
    sources += ['UnifiedTheory/Audit/'+name+'.lean' for name in [
        'KFCausalLongitudinalDomain','KFCausalRegularizedLongitudinalChart','KFCausalRegularizedLongitudinalPullback']]
    hashes = {p:hashlib.sha256((root/p).read_bytes()).hexdigest() for p in sources}
    assert all(hashes[p]==h for p,h in previous['source_sha256'].items())
    report = dict(homogeneous_matrix_cases=cases,precision_comparisons=comparison,
        regularized_translation_samples=flow,source_sha256=hashes,
        numerical_environment=dict(mpmath=mp.__version__,sympy=sy.__version__),
        lean_toolchain=(root/'lean-toolchain').read_text().strip(),
        external_domain_reference='https://arxiv.org/pdf/quant-ph/0103153',
        scope=('Lean verifies the formal half-line differential expression and deficiency profiles; '
               'the self-adjoint-extension obstruction uses the cited operator-domain theorem and '
               'is not claimed to be a Lean-verified unbounded-operator result. The proposed '
               'epsilon>0 chart has a proved global positive translation flow and an L2 '
               'Jacobian pullback. It changes the longitudinal model. These finite one-mode '
               'spectra do not prove divergence or convergence of the full six-mode Hamiltonian. '
               'A quantum Hamiltonian domain, regulator removal, physical identification and '
               'a TOE remain unproved.'))
    target = root/'data/longitudinal_domain_audit.json'
    target.write_text(json.dumps(report,indent=2)+'\n')
    print(target,':',len(cases),'matrix cases,',len(flow),'translation checks,',len(hashes),'source hashes.',flush=True)


if __name__ == '__main__':
    main()
