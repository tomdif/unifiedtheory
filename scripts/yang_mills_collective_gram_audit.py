"""Check actual collective Gram response; preserve 7322 prior checks."""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from free_balanced_hamiltonian_audit import ROOT, STANDARD_AXIOMS, local_dependencies, sha256
from yang_mills_variance_dissipation_audit import TARGETS as PREVIOUS_TARGETS, proof_code

NEW_TARGETS = ['UnifiedTheory.Clay.YangMills.CompactGramResponse', 'UnifiedTheory.Clay.YangMills.WilsonRowGram', 'UnifiedTheory.Clay.YangMills.WilsonMixedGroundResponse', 'UnifiedTheory.Clay.YangMills.WilsonCollectiveGram']
TARGETS = PREVIOUS_TARGETS + NEW_TARGETS
CHECK = 'scripts/CheckYangMillsCollectiveGram.lean'
PREVIOUS_REPORT = 'data/yang_mills_variance_dissipation_audit.json'
PREVIOUS_COUNT = 7322
NEW_COUNT = 39
SCOPE = 'Actual SU(2) Wilson collective local response is controlled by the absolute row sums of its centered likelihood Gram matrix, retaining correlations between input-link changes. For actual row nu_u, s_i(v)=p_(R_i u)(v)/p_u(v)-1 is continuous, has zero mean, and depends on output v only through link e_i. Its Gram G_ij(u)=E_nu_u[s_i*s_j] is symmetric positive semidefinite with proved diagonal bound B(beta,q_i)=(exp(4*beta*norm(q_i-1))-1)^2. For distinct links, G_ij+1=Z(u)*Z(R_i R_j u)/(Z(R_i u)*Z(R_j u)), where Z is the actual row partition function. If their affected spatial plaquette sets are disjoint, the bare spatial action cancels and G_ij=exp(Delta_i Delta_j log g)-1 for the constructed original ground amplitude g. For real amplitudes a_i, a uniform absolute row-sum bound kappa on M_ij=a_i*a_j*G_ij implies sum_i a_i^2 E_i(P f)<=kappa*(Var_pi f-Var_pi(P f)), and the time sum through k steps is at most kappa*(Var_pi f-Var_pi(P^k f)). Gauge-invariant sources use the already proved identification with original normalized physical transfer powers. The upper Gram bound is an explicit hypothesis; its uniform weak-coupling control is not proved. A separate collective whole-slab lower bound then conditionally gives contraction kappa/(1+kappa). No mass gap, continuum limit or surviving physical excitation is inferred. All twelve Clay obligations remain open.'
