"""Check canonical actual physical Gram projection; preserve 7458 prior checks."""
import json
import os
from pathlib import Path
import re
import subprocess
import tempfile

from free_balanced_hamiltonian_audit import ROOT, STANDARD_AXIOMS, local_dependencies, sha256
from yang_mills_haar_response_audit import TARGETS as PREVIOUS_TARGETS, proof_code

NEW_TARGETS = ['UnifiedTheory.Clay.YangMills.CompactPhysicalProjection', 'UnifiedTheory.Clay.YangMills.WilsonPhysicalScore', 'UnifiedTheory.Clay.YangMills.WilsonPhysicalGram', 'UnifiedTheory.Clay.YangMills.WilsonPhysicalDissipation']
TARGETS = PREVIOUS_TARGETS + NEW_TARGETS
CHECK = 'scripts/CheckYangMillsPhysicalGram.lean'
PREVIOUS_REPORT = 'data/yang_mills_haar_response_audit.json'
PREVIOUS_COUNT = 7458
NEW_COUNT = 33
SCOPE = 'Canonical physical likelihood scores are constructed directly from the actual original gauge-averaged Wilson transfer: s_phys(u,w;v)=P(w,v)/P(u,v)-1. They are continuous and gauge invariant in the output, have zero mean under the actual raw row law, and preserve all continuous physical source pairings and centered responses. Every pure-gauge input change has identically zero physical score. The difference from the raw score is orthogonal to every continuous gauge-invariant test. For any fixed finite response family and baseline input, the actual raw Gram matrix splits exactly as M_raw=M_phys+Gram(removed). Hence 0<=M_phys<=M_one_gauge_residual<=M_raw in quadratic-form order, for every previous choice of one nuisance gauge score. More generally M_phys is minimal among all continuous score families representing those same physical pairings under the same raw row law. Its entries equal the corresponding full-transition density integrals, so it is not a surrogate matrix. A uniform signed bound on M_phys gives the original-transfer response dissipation and whole-time sum with that same coefficient, and the previous conditional contraction formula. No regular gauge fixing or choice of gauge transformation is needed. No numerical uniform bound or strict improvement of the optimal upper constant is proved. Projected scores are not asserted local, and no finite-family bound is silently extended to the Haar-indexed family. Ground-law factorization, physical-scale control, continuum survival and all twelve Clay obligations remain open.'
