import os
from pathlib import Path
import re
import subprocess
import tempfile

from free_balanced_hamiltonian_audit import ROOT, STANDARD_AXIOMS, local_dependencies, sha256
from yang_mills_connected_cluster_audit import TARGETS as PREVIOUS_TARGETS, proof_code

